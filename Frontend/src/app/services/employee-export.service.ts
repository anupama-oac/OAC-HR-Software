    addWideRow('Current / Temporary Address', personal.temporaryAddress);
    addWideRow('Permanent Address', personal.permanentAddress);
    currentRow++; // Spacing

    // SECTION 3: STATUTORY & IDENTIFICATION
    addSectionHeader('3. STATUTORY & IDENTIFICATION DETAILS');
    addTwoColRow('Aadhar Number', statutory.adharNo, 'PAN Number', statutory.panNumber);
