    addTwoColRow('IFSC Code', account.ifseCode, 'Branch Name', account.branchName);
    addTwoColRow('Payment Mode', account.modeOfPayment, 'Payment Frequency', account.paymentFrequency);
    currentRow++; // Spacing

    // SECTION 5: NOMINEE DETAILS
    addSectionHeader('5. NOMINEE DETAILS');
    addTwoColRow('Nominee Name', nominee.nomineeName, 'Relationship', nominee.nomineeRelation);
    addTwoColRow('Nominee Contact Number', nominee.nomineeContactNumber, 'Nominee Aadhar Number', nominee.aadhaarNumber);
    currentRow++; // Spacing

    // SECTION 6: QUALIFICATIONS & EDUCATION
